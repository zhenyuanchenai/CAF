def print_args(args, cfg):
    print("***************")
    print("** Arguments **")
    print("***************")
    optkeys = list(args.__dict__.keys())
    optkeys.sort()
    for key in optkeys:
        print("{}: {}".format(key, args.__dict__[key]))
    print("************")
    print("** Config **")
    print("************")
    print(cfg)


def reset_cfg(cfg, args):
    if args.root:
        cfg.DATASET.ROOT = args.root

    if args.output_dir:
        cfg.OUTPUT_DIR = args.output_dir

    if args.resume:
        cfg.RESUME = args.resume

    if args.seed >= 0:
        cfg.SEED = args.seed

    if args.source_domains:
        cfg.DATASET.SOURCE_DOMAINS = args.source_domains

    if args.target_domains:
        cfg.DATASET.TARGET_DOMAINS = args.target_domains

    if args.transforms:
        cfg.INPUT.TRANSFORMS = args.transforms

    if args.trainer:
        cfg.TRAINER.NAME = args.trainer

    if args.backbone:
        cfg.MODEL.BACKBONE.NAME = args.backbone

    if args.head:
        cfg.MODEL.HEAD.NAME = args.head

    if getattr(args, "lambda_margin", None) is not None:
        cfg.TRAINER.CAF.LAMBDA_MARGIN = args.lambda_margin

    if getattr(args, "lambda_text", None) is not None:
        cfg.TRAINER.CAF.LAMBDA_TEXT = args.lambda_text


def extend_cfg(cfg):
    from yacs.config import CfgNode as CN

    cfg.DATASET.SUBSAMPLE_CLASSES = "all"
    cfg.DATASET.MANIFEST = ""
    cfg.DATASET.TRAIN_MANIFEST = ""
    cfg.TRAINER.CAF = CN()
    cfg.TRAINER.CAF.N_CTX = 8
    cfg.TRAINER.CAF.PROMPT_DEPTH = 12
    cfg.TRAINER.CAF.PREC = "amp"
    cfg.TRAINER.CAF.LAMBDA_MARGIN = 4.0
    cfg.TRAINER.CAF.LAMBDA_TEXT = 2.5
    cfg.TRAINER.CAF.ALPHA_INIT = 16.0
    cfg.TRAINER.CAF.BETA_INIT = 10.849894523620605
    cfg.TRAINER.CAF.EMA_RATE = 0.01
    cfg.TRAINER.CAF.GATE_LR = 0.001
    cfg.TRAINER.CAF.GATE_WARMUP_LR = 0.0000025
    cfg.TRAINER.CAF.INIT_PROMPT = ""
    cfg.TRAINER.CAF.REFERENCE = ""
    cfg.TRAINER.CAF.CLIP_PATH = ""
    cfg.TRAINER.CAF.EPOCH_SEED_OFFSET = 0
    cfg.TRAINER.CAF.CHECKPOINTING = True
    cfg.TRAINER.CAF.EVAL_ONLY = False
    cfg.TEST.READOUT = "fusion"


def setup_cfg(args):
    cfg = get_cfg_default()
    extend_cfg(cfg)

    # 1. From the dataset config file
    if args.dataset_config_file:
        cfg.merge_from_file(args.dataset_config_file)

    # 2. From the method config file
    if args.config_file:
        cfg.merge_from_file(args.config_file)

    # 3. From input arguments
    reset_cfg(cfg, args)

    # 4. From optional input arguments
    cfg.merge_from_list(args.opts)

    cfg.TRAINER.CAF.EVAL_ONLY = args.eval_only
    cfg.freeze()

    return cfg


def main(args):
    cfg = setup_cfg(args)
    if cfg.SEED >= 0:
        print("Setting fixed seed: {}".format(cfg.SEED))
        set_random_seed(cfg.SEED)
    setup_logger(cfg.OUTPUT_DIR)

    if torch.cuda.is_available() and cfg.USE_CUDA:
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True
        torch.backends.cuda.matmul.allow_tf32 = False
        torch.backends.cudnn.allow_tf32 = False

    torch.set_num_threads(1)
    torch.use_deterministic_algorithms(True)
    print_args(args, cfg)
    print("Collecting env info ...")
    print("** System info **\n{}\n".format(collect_env_info()))

    trainer = build_trainer(cfg)

    if args.eval_only:
        trainer.load_model(args.model_dir, epoch=args.load_epoch)
        trainer.test()
        return

    if not args.no_train:
        trainer.train()


